"""Congruence of the boxed images (closes 'unique up to symmetry'): the local certificate has one Krawczyk box per
image of the minimizer in the fundamental domain, and jobs/sym_cert.py proves, image by image, that the zero in
each box is a symmetric configuration Y(s*_k) with value D*.  Here we prove that all these configurations are
congruent: for every image k there is a map sigma of the symmetric parameters that sends Y(s) to a congruent
configuration (an isometry), with sigma(K_k) contained in the symmetric Krawczyk box Z_0 of image 0.  Since the
zero of the symmetric system in Z_0 is unique, sigma(s*_k) = s*_0, so Y(s*_k) is congruent to Y(s*_0).

Admissible sigma (each is an isometry of the family):
  N5_best, s = (c, e):    only the identity.
  N6_best, s = (a, b, h): sign changes of any coordinates.  Changing the sign of a, b or h is the reflection in
                          x = 0, y = 0 or z = 0; each conjugates the group generated by the rotation by 120 degrees
                          about the z-axis and the half-turn about the x-axis into itself, so it maps the orbit of
                          (a, b, h) onto the orbit of the reflected point.
The selection of sigma is numerical (nearest), the containment check is rigorous (Arb).
usage: python jobs/congruence_cert.py N5_best|N6_best    writes certificates/congruence_<NAME>.json
"""
import sys, os, json, glob, itertools
import flint
from flint import arb
flint.ctx.prec = 128
HERE = os.path.dirname(os.path.abspath(__file__)); CERT = os.path.join(HERE, '..', 'certificates')
name = sys.argv[1]
files = sorted(glob.glob(os.path.join(CERT, f'symcert_{name}_img*.json')))
certs = [json.load(open(f)) for f in files]
assert certs and all('s_enclosure' in c for c in certs), 'run jobs/sym_cert.py for every image first'
c0 = next(c for c in certs if c['image'] == 0)
k = len(c0['s_box_mid']) - 1                     # the last coordinate is D
# Z_0 has exact (binary) midpoints printed here to 40 digits; parsing them back is accurate to ~1e-40, so the box
# below, with radius shrunk by the factor 1 - 1e-6 (rk >= 1e-30), lies inside the true Z_0: the test is conservative.
Z0 = [arb(m, c0['s_box_radius'] * (1 - 1e-6)) for m in c0['s_box_mid']]
sigmas = [(1,) * k] if name.startswith('N5') else list(itertools.product((1, -1), repeat=k))
out = []
for c in certs:
    K = [arb(x) for x in c['s_enclosure']]
    best = min(sigmas, key=lambda sg: sum(abs(float((sg[i] * K[i]).mid()) - float(Z0[i].mid())) for i in range(k)))
    sK = [best[i] * K[i] for i in range(k)] + [K[k]]
    inside = all(Z0[i].contains(sK[i]) for i in range(k + 1))
    out.append(dict(image=c['image'], sigma=list(best), contained_in_Z0=bool(inside), verified_image=bool(c['verified'])))
    print(f"{name} image {c['image']}: sigma {best}, sigma(K) inside Z_0: {inside}")
ok = all(o['contained_in_Z0'] and o['verified_image'] for o in out)
res = dict(name=name, images=out, congruent=ok, kernel='arb (python-flint)', label='Krawczyk-verified (Arb)')
json.dump(res, open(os.path.join(CERT, f'congruence_{name}.json'), 'w'), indent=1)
print('ALL IMAGES CONGRUENT (Arb)' if ok else 'NOT VERIFIED')
